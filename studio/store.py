"""
State store for Davis Studio.

Job and chat state lives as JSON files on the `app-data` branch of this
repository, which the Android app reads through the GitHub API. Finished
videos are attached to the `davis-videos` release; reference uploads arrive
on the `davis-inbox` release.
"""

import json
import os
import subprocess
import time

DATA_BRANCH = "app-data"
DATA_DIR = os.path.abspath(os.environ.get("STUDIO_DATA_DIR", "../app-data-checkout"))
VIDEOS_RELEASE = "davis-videos"
INBOX_RELEASE = "davis-inbox"

_ready = False


def _run(cmd, cwd=None, check=True):
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} failed: {result.stderr.strip()[-400:]}")
    return result


def repo_slug() -> str:
    return os.environ.get("GITHUB_REPOSITORY", "")


def _setup():
    """Check out the app-data branch into DATA_DIR, creating it if missing."""
    global _ready
    if _ready:
        return
    if os.path.isdir(os.path.join(DATA_DIR, ".git")) or os.path.isfile(os.path.join(DATA_DIR, ".git")):
        _ready = True
        return

    fetched = _run(["git", "fetch", "origin", DATA_BRANCH], check=False).returncode == 0
    if fetched:
        _run(["git", "worktree", "add", "-B", DATA_BRANCH, DATA_DIR, f"origin/{DATA_BRANCH}"])
    else:
        _run(["git", "worktree", "add", "--detach", DATA_DIR])
        _run(["git", "checkout", "--orphan", DATA_BRANCH], cwd=DATA_DIR)
        _run(["git", "rm", "-rf", "--quiet", "."], cwd=DATA_DIR, check=False)
        with open(os.path.join(DATA_DIR, "README.md"), "w") as f:
            f.write("Davis Studio app data. Managed automatically — do not edit.\n")
        with open(os.path.join(DATA_DIR, "index.json"), "w") as f:
            json.dump({"jobs": []}, f)
        with open(os.path.join(DATA_DIR, "vercel.json"), "w") as f:
            json.dump({"git": {"deploymentEnabled": False}}, f)

    _run(["git", "config", "user.name", "Davis Studio"], cwd=DATA_DIR)
    _run(["git", "config", "user.email", "davis-studio@users.noreply.github.com"], cwd=DATA_DIR)
    _ready = True


def _push(message: str):
    _run(["git", "add", "-A"], cwd=DATA_DIR)
    if _run(["git", "diff", "--cached", "--quiet"], cwd=DATA_DIR, check=False).returncode == 0:
        return
    _run(["git", "commit", "--quiet", "-m", message], cwd=DATA_DIR)
    for attempt in range(5):
        if _run(["git", "push", "--quiet", "origin", f"HEAD:{DATA_BRANCH}"], cwd=DATA_DIR, check=False).returncode == 0:
            return
        # Another job pushed first: replay our commit on top of theirs.
        _run(["git", "pull", "--quiet", "--rebase", "origin", DATA_BRANCH], cwd=DATA_DIR, check=False)
        time.sleep(1 + attempt)
    raise RuntimeError("Could not push app data after 5 attempts")


def read_json(rel_path: str, default=None):
    _setup()
    path = os.path.join(DATA_DIR, rel_path)
    if not os.path.exists(path):
        return default
    with open(path) as f:
        return json.load(f)


def write_json(rel_path: str, data, message: str):
    _setup()
    path = os.path.join(DATA_DIR, rel_path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    _push(message)


def save_job(job: dict):
    """Persist a job and refresh its summary row in index.json."""
    _setup()
    _run(["git", "pull", "--quiet", "--rebase", "origin", DATA_BRANCH], cwd=DATA_DIR, check=False)

    job["updated_at"] = int(time.time())
    path = os.path.join(DATA_DIR, "jobs", f"{job['id']}.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(job, f, indent=1, ensure_ascii=False)

    index_path = os.path.join(DATA_DIR, "index.json")
    index = {"jobs": []}
    if os.path.exists(index_path):
        with open(index_path) as f:
            index = json.load(f)
    summary = {
        key: job.get(key)
        for key in ("id", "created_at", "updated_at", "mode", "status", "step",
                    "progress", "title", "topic", "error", "video_url", "thumb_url")
    }
    index["jobs"] = [j for j in index.get("jobs", []) if j.get("id") != job["id"]]
    index["jobs"].insert(0, summary)
    index["jobs"].sort(key=lambda j: j.get("created_at") or 0, reverse=True)
    with open(index_path, "w") as f:
        json.dump(index, f, indent=1, ensure_ascii=False)

    _push(f"job {job['id']}: {job.get('status')}")


def _ensure_release(tag: str, title: str, notes: str):
    if _run(["gh", "release", "view", tag], check=False).returncode != 0:
        _run(["gh", "release", "create", tag, "--title", title, "--notes", notes])


def upload_to_release(local_path: str, asset_name: str) -> str:
    """Attach a file to the videos release and return its public URL."""
    _ensure_release(VIDEOS_RELEASE, "Davis Studio videos",
                    "Videos generated by Davis Studio. Managed automatically.")
    staged = os.path.join(os.path.dirname(os.path.abspath(local_path)), asset_name)
    if os.path.abspath(local_path) != staged:
        os.replace(local_path, staged)
    _run(["gh", "release", "upload", VIDEOS_RELEASE, staged, "--clobber"])
    return f"https://github.com/{repo_slug()}/releases/download/{VIDEOS_RELEASE}/{asset_name}"


def download_reference(job_id: str, dest_dir: str) -> str:
    """Fetch the uploaded reference video for a job from the inbox release."""
    os.makedirs(dest_dir, exist_ok=True)
    _run(["gh", "release", "download", INBOX_RELEASE, "--pattern", f"{job_id}.*",
          "--dir", dest_dir, "--clobber"])
    for name in os.listdir(dest_dir):
        if name.startswith(job_id + "."):
            return os.path.join(dest_dir, name)
    raise RuntimeError("Reference video was not found in the upload inbox")


def delete_reference(job_id: str):
    """Remove the uploaded reference once analysed, so it is not kept public."""
    listing = _run(["gh", "release", "view", INBOX_RELEASE, "--json", "assets"], check=False)
    if listing.returncode != 0:
        return
    for asset in json.loads(listing.stdout).get("assets", []):
        if asset["name"].startswith(job_id + "."):
            _run(["gh", "release", "delete-asset", INBOX_RELEASE, asset["name"], "--yes"], check=False)
